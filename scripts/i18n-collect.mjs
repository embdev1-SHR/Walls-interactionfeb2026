/**
 * i18n-collect.mjs — every English/Malayalam pair the wall shows or says
 * ══════════════════════════════════════════════════════════════════════════
 *
 *     node scripts/i18n-collect.mjs
 *
 * WHY
 *   The wall's content is written as { en, ml } pairs, in 77 pages. Hindi and
 *   Kannada were added later (the universal language setting), and adding
 *   `hi:` and `kn:` to every pair in every page would touch everything for the
 *   sake of a lookup. Instead the translations live in ONE table per language,
 *   keyed by the English text:
 *
 *     content/i18n/hi.json    { "Good morning! Shall we play?": "सुप्रभात! ..." }
 *     content/i18n/kn.json    { "Good morning! Shall we play?": "ಶುಭೋದಯ! ..." }
 *
 *   and js/wall-settings.js looks a pair up there at runtime. A pair with no
 *   entry simply shows its English — nothing breaks while translation catches up.
 *
 * WHAT THIS DOES
 *   Reads every small object literal in games/ and js/ that pairs English
 *   (en:, or name:/word: in older data) with Malayalam (ml:), and writes
 *     content/i18n/strings.json      en -> ml, the translator's context
 *     content/i18n/<lang>.missing.json   what each table still lacks
 *     js/i18n-data.js                the runtime tables, plus a map from every
 *                                    Malayalam spelling back to its English,
 *                                    so a Malayalam line can be re-voiced.
 *   A script, not JSON, because the app runs from file:// where a <script>
 *   tag never fails.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'content', 'i18n');
const LANGS = ['hi', 'kn'];
const SKIP_FILES = /^(i18n-data|voice-manifest|credits-data)\.js$/;

const STR = String.raw`'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"`;
/* A flat object literal: no nested braces, and short — the { en, ml } pairs,
   the { name, ml } menu entries and the { word, ml } cards all look like this. */
const OBJ = /\{[^{}]{0,600}\}/g;
const KEYS = {};
function keyRe(k) {
  return KEYS[k] || (KEYS[k] = new RegExp(String.raw`(?:^|[\s,{])${k}\s*:\s*(?:${STR})`));
}

/** JS string-literal escapes to the text the page actually shows. */
function unescape(s) {
  return s.replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)))
          .replace(/\\(['"\\])/g, '$1').replace(/\\n/g, '\n');
}

function field(obj, k) {
  const m = keyRe(k).exec(obj);
  return m ? unescape(m[1] ?? m[2] ?? '').trim() : null;
}

const HAS_ML = /[\u0D00-\u0D7F]/;

/**
 * pairs:    en -> ml (the first Malayalam seen, for the translator's context)
 * variants: en -> every Malayalam spelling it is paired with anywhere
 *           ("Rose" is റോസ് in one page and റോസപ്പൂവ് in another)
 */
export function collect() {
  const pairs = new Map(), variants = new Map();
  for (const d of ['games', 'js']) {
    for (const f of readdirSync(join(ROOT, d))) {
      if (!/\.(html|js)$/.test(f) || SKIP_FILES.test(f)) continue;
      const src = readFileSync(join(ROOT, d, f), 'utf8');
      OBJ.lastIndex = 0;
      let m;
      while ((m = OBJ.exec(src))) {
        const ml = field(m[0], 'ml');
        const en = field(m[0], 'en') ?? field(m[0], 'name') ?? field(m[0], 'word');
        if (!ml || !en || !HAS_ML.test(ml)) continue;
        if (/\$\{|[<>]/.test(en) || HAS_ML.test(en)) continue;
        if (!pairs.has(en)) pairs.set(en, ml);
        if (!variants.has(en)) variants.set(en, new Set());
        variants.get(en).add(ml);
      }
    }
  }
  return { pairs, variants };
}

function main() {
  const { pairs, variants } = collect();
  mkdirSync(DIR, { recursive: true });
  const sorted = [...pairs.keys()].sort((a, b) => a.localeCompare(b));
  writeFileSync(join(DIR, 'strings.json'),
    JSON.stringify(Object.fromEntries(sorted.map((k) => [k, pairs.get(k)])), null, 1), 'utf8');

  const tables = {};
  for (const l of LANGS) {
    const f = join(DIR, l + '.json');
    tables[l] = existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : {};
    const missing = sorted.filter((k) => !tables[l][k]);
    const mf = join(DIR, l + '.missing.json');
    console.log(`${l}: ${sorted.length - missing.length}/${sorted.length} translated`);
    if (missing.length) {
      writeFileSync(mf, JSON.stringify(missing, null, 1), 'utf8');
      console.log(`   ${missing.length} missing -> content/i18n/${l}.missing.json`);
    } else if (existsSync(mf)) unlinkSync(mf);
  }

  const mlToEn = {};
  for (const [en, set] of variants) for (const ml of set) if (!mlToEn[ml]) mlToEn[ml] = en;

  writeFileSync(join(ROOT, 'js', 'i18n-data.js'), [
    '/* GENERATED by scripts/i18n-collect.mjs from content/i18n/*.json - do not edit.',
    ' * I18N_TABLES: English text -> Hindi / Kannada.',
    ' * I18N_ML_EN:  every Malayalam spelling -> its English, so a Malayalam',
    ' *              line can be found and re-voiced in another language.',
    ' * Read by js/wall-settings.js. */',
    'window.I18N_TABLES = ' + JSON.stringify(tables) + ';',
    'window.I18N_ML_EN = ' + JSON.stringify(mlToEn) + ';',
    ''
  ].join('\n'), 'utf8');
  console.log(`${sorted.length} distinct English strings with a Malayalam partner`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
